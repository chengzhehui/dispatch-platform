import { browserLaunchOptions } from './browser-options.mjs'
import { chromium } from 'playwright'
import fs from 'node:fs'
import assert from 'node:assert/strict'

fs.mkdirSync('artifacts', { recursive: true })
const browser = await chromium.launch(browserLaunchOptions)
const page = await browser.newPage({ viewport: { width: 1536, height: 1024 } })
page.setDefaultTimeout(60000)
const errors = []
page.on('pageerror', error => errors.push(error.message))
page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
const engine = `document.getElementById('app').__vue_app__._instance.setupState.engine`
const read = expression => page.evaluate(`(() => {const e=${engine};return (${expression})})()`)
const wait = expression => page.waitForFunction(`(() => {const e=${engine};return e && (${expression})})()`, null, { timeout: 60000 })
async function clickGround(x, z) {
  const point = await page.evaluate(`(() => {const e=${engine}, p=e.camera.position.clone().set(${x}, .1, ${z}).project(e.camera), r=e.host.getBoundingClientRect();return {x:r.x+(p.x+1)/2*r.width,y:r.y+(1-p.y)/2*r.height}})()`)
  await page.mouse.click(point.x, point.y)
}
try {
  await page.goto('http://localhost:5188')
  await wait('e.workers.length === 12 && e.tiles.visibleTiles.size > 0')
  await page.getByLabel('今日焊工人数').fill('2')
  await page.getByRole('button', { name: '设置人数', exact: true }).click()
  await page.locator('.simulation-controls select').selectOption('4')
  await page.getByRole('button', { name: '预备区', exact: true }).click()
  const actorPoint = await page.evaluate(`(() => {const e=${engine}, p=e.workers[0].visual.root.position.clone();p.y+=1;p.project(e.camera);const r=e.host.getBoundingClientRect();return {x:r.x+(p.x+1)/2*r.width,y:r.y+(1-p.y)/2*r.height}})()`)
  await page.mouse.click(actorPoint.x, actorPoint.y)
  assert.equal(await read('e.selected.size'), 1)
  await page.evaluate(`(() => {const e=${engine},s=e.site;e.controls.target.set(s.minX+6,3,s.minZ+20);e.camera.position.set(s.minX-34,48,s.minZ+80);e.controls.update()})()`)
  const [x, z] = await read('[e.site.minX+22,e.site.minZ+22]')
  await clickGround(x, z)
  await wait('e.moveEffects.orders.size === 1')
  assert.equal(await read('[...e.moveEffects.orders.values()][0].visual.convergence.visible'), true)
  await page.screenshot({ path: 'artifacts/click-convergence.png' })
  const anchor = await read('[...e.moveEffects.orders.values()][0].point')
  assert.ok(Math.hypot(anchor[0] - x, anchor[2] - z) < .5, 'marker stays at mouse click')
  const phase = await read('[...e.moveEffects.orders.values()][0].visual.arcs.rotation.y')
  await page.waitForTimeout(1400)
  assert.equal(await read('e.moveEffects.orders.size'), 1, 'marker outlives click burst')
  assert.equal(await read('[...e.moveEffects.orders.values()][0].visual.convergence.visible'), false)
  assert.notEqual(await read('[...e.moveEffects.orders.values()][0].visual.arcs.rotation.y'), phase)
  await page.keyboard.press('Escape')
  assert.equal(await read('e.selected.size'), 0)
  assert.equal(await read('e.moveEffects.orders.size'), 1, 'deselection preserves active marker')
  await page.getByRole('button', { name: '暂停移动', exact: true }).click()
  await page.screenshot({ path: 'artifacts/move-command.png' })
  console.log('PASS: real canvas click, exact anchor, persistent pulse and deselection')

  await page.getByRole('button', { name: '全选', exact: true }).click()
  await clickGround(x + 8, z + 10)
  assert.equal(await read('e.moveEffects.orders.size'), 1, 'new order replaces superseded marker')
  assert.equal(await read('[...e.moveEffects.orders.values()][0].members.size'), 2)
  await page.waitForTimeout(350)
  await page.screenshot({ path: 'artifacts/move-command-group.png' })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.waitForTimeout(300)
  assert.equal(await read('[...e.moveEffects.orders.values()][0].visual.root.visible'), true)
  await page.screenshot({ path: 'artifacts/move-command-mobile.png', fullPage: true })
  await page.setViewportSize({ width: 1536, height: 1024 })
  await page.locator('.simulation-controls select').selectOption('60')
  await page.getByRole('button', { name: '继续移动', exact: true }).click()
  await wait('e.workers.every(w=>!w.target) && e.moveEffects.orders.size === 0')
  assert.equal(await read("!!e.scene.getObjectByName('move-command-effect')"), false)
  console.log('PASS: formation grouping, retarget, pause, mobile render and arrival cleanup')

  await clickGround(x + 16, z + 3)
  assert.equal(await read('e.moveEffects.orders.size'), 1)
  await page.getByRole('button', { name: '停止移动', exact: true }).click()
  assert.equal(await read('e.moveEffects.orders.size'), 0)
  await clickGround(x, z)
  await page.getByLabel('今日焊工人数').fill('0')
  await page.getByRole('button', { name: '设置人数', exact: true }).click()
  assert.equal(await read('e.moveEffects.orders.size'), 0)
  assert.deepEqual(errors, [])
  console.log('PASS: stop/deletion cleanup; no browser runtime errors')
} finally { await browser.close() }
