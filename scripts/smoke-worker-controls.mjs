import { browserLaunchOptions } from './browser-options.mjs'
import { chromium } from 'playwright'
import assert from 'node:assert/strict'
import fs from 'node:fs'

fs.mkdirSync('artifacts', { recursive: true })
const browser = await chromium.launch(browserLaunchOptions)
const page = await browser.newPage({ viewport: { width: 1536, height: 1024 } })
const errors = []
page.on('pageerror', error => errors.push(error.message))
page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
page.setDefaultTimeout(60000)
const engine = `document.getElementById('app').__vue_app__._instance.setupState.engine`
const read = expression => page.evaluate(`(() => {const e=${engine};return (${expression})})()`)
const run = code => page.evaluate(`(() => {const e=${engine};${code}})()`)
const wait = expression => page.waitForFunction(`(() => {const e=${engine};return e && (${expression})})()`, null, { timeout: 60000 })
const pos = () => read('e.getControlledWorker().position.slice()')
const distance = (a, b) => Math.hypot(...a.map((value, i) => value - b[i]))
async function hold(key, duration = 350) {
  await page.keyboard.down(key); await page.waitForTimeout(duration); await page.keyboard.up(key); await page.waitForTimeout(60)
}
try {
  await page.goto('http://localhost:5188')
  await wait('e.workers.length === 12 && e.tiles.visibleTiles.size > 0')
  const box = await page.locator('.scene-host').boundingBox()
  const mouse = { x: box.x + box.width * 0.48, y: box.y + box.height * 0.65 }
  await page.mouse.move(mouse.x, mouse.y)
  await run(`window.zoomFrames=[];let count=45;function sample(){window.zoomFrames.push(e.camera.position.distanceTo(e.controls.target));if(--count)requestAnimationFrame(sample)};requestAnimationFrame(sample)`)
  await page.mouse.wheel(0, -240)
  await page.waitForFunction('window.zoomFrames.length === 45')
  const zoomFrames = await page.evaluate('window.zoomFrames')
  assert.ok(zoomFrames[0] - zoomFrames.at(-1) > 1)
  assert.ok(new Set(zoomFrames.map(value => value.toFixed(3))).size > 6, 'wheel changes viewpoint across many frames')
  console.log('PASS: review wheel zoom eases over multiple frames')

  await page.getByRole('button', { name: '预备区', exact: true }).click()
  await page.getByRole('button', { name: '焊工视角', exact: true }).click()
  await wait('e.cameraMode === "worker" && e.workerController.distance >= 5.9')
  assert.equal(await read('e.getControlledWorker().visual.root.visible'), true)
  const review = await read('({position:e.reviewView.position.toArray(),target:e.reviewView.target.toArray()})')
  const firstId = await read('e.followedId')
  await run('e.command([e.site.minX+30,.1,e.site.minZ+30])')
  assert.ok(await read('e.getControlledWorker().target'))
  await hold('w')
  assert.equal(await read('e.getControlledWorker().target'), null)
  assert.equal(await read('e.moveEffects.orders.size'), 0)
  const start = await pos()
  await hold('s')
  assert.ok(distance(start, await pos()) > .5)
  const afterBack = await pos()
  await hold('a')
  const afterLeft = await pos()
  assert.ok(distance(afterBack, afterLeft) > .5)
  assert.equal(await read('e.selected.size'), 1, 'A moves left instead of selecting all')
  await hold('d')
  assert.ok(distance(afterLeft, await pos()) > .5)
  const still = await pos(); await page.waitForTimeout(250)
  assert.ok(distance(still, await pos()) < .001)
  console.log('PASS: WASD, manual takeover, selection isolation and release-to-stop')

  const yaw = await read('e.getControlledWorker().visual.root.rotation.y')
  await page.mouse.move(mouse.x, mouse.y)
  await page.mouse.down({ button: 'left' })
  await page.mouse.move(mouse.x + 80, mouse.y - 12, { steps: 6 })
  await page.mouse.up({ button: 'left' })
  assert.equal(await read('e.getControlledWorker().visual.root.rotation.y'), yaw)
  assert.ok(Math.abs(await read('e.workerController.yaw') - yaw) > .2)
  await page.mouse.down({ button: 'right' })
  await page.mouse.move(mouse.x + 140, mouse.y + 8, { steps: 6 })
  const facing = await read('e.getControlledWorker().visual.root.rotation.y')
  assert.ok(Math.abs(facing - yaw) > .2)
  assert.equal(await read('e.workerController.yaw'), facing)
  const beforeBoth = await pos()
  await page.mouse.down({ button: 'left' })
  await page.waitForTimeout(350)
  await page.mouse.up({ button: 'right' }); await page.mouse.up({ button: 'left' })
  const afterBoth = await pos()
  assert.ok(distance(beforeBoth, afterBoth) > .7)
  const forwardDot = (afterBoth[0] - beforeBoth[0]) * Math.sin(facing) + (afterBoth[2] - beforeBoth[2]) * Math.cos(facing)
  assert.ok(forwardDot > .7, 'both mouse buttons walk in the mouse-controlled facing')
  assert.equal(await read('e.moveEffects.orders.size'), 0, 'mouse look never issues RTS destination orders')
  console.log('PASS: independent left orbit, right steering and combined-button walking')

  const ground = (await pos())[1]
  await page.keyboard.down('Space')
  await page.waitForTimeout(200)
  assert.ok(await read('e.getControlledWorker().jump.height') > .5)
  assert.equal((await pos())[1], ground)
  await page.screenshot({ path: 'artifacts/worker-jump.png' })
  await page.keyboard.up('Space')
  await wait('e.getControlledWorker().jump === null')
  assert.equal((await pos())[1], ground)
  const z = await pos()
  await page.keyboard.down('w'); await page.waitForTimeout(200)
  await page.evaluate('window.dispatchEvent(new Event("blur"))')
  const blurred = await pos(); await page.waitForTimeout(250)
  assert.ok(distance(blurred, await pos()) < .001)
  await page.keyboard.up('w')
  assert.ok(distance(z, blurred) > .3)
  await page.getByLabel('今日焊工人数').focus()
  const inputPos = await pos(); await hold('w', 180)
  assert.ok(distance(inputPos, await pos()) < .001)
  await page.mouse.click(mouse.x, mouse.y)
  await hold('w', 180)
  assert.ok(distance(inputPos, await pos()) > .3, 'clicking canvas resumes keyboard control after editing')
  console.log('PASS: flat jump/landing, stable logical elevation, blur and input-focus safety')

  await page.mouse.move(mouse.x, mouse.y)
  const beforeZoom = await read('e.workerController.distance')
  await page.mouse.wheel(0, 260)
  const targetZoom = await read('e.workerController.targetDistance')
  assert.ok(targetZoom > beforeZoom)
  await wait('Math.abs(e.workerController.distance - e.workerController.targetDistance) < .01')
  await page.locator('.worker-settings summary').click()
  await page.getByLabel('手动移动速度').selectOption('8')
  assert.equal(await read('e.workerController.moveSpeed'), 8)
  await page.getByLabel('焊工相机距离').fill('0')
  await wait('e.workerController.distance < .1')
  assert.equal(await read('e.getControlledWorker().visual.root.visible'), false)
  await page.getByRole('button', { name: '恢复背后视角', exact: true }).click()
  await wait('e.workerController.distance > 5.9')
  assert.equal(await read('e.getControlledWorker().visual.root.visible'), true)
  await page.locator('.worker-settings summary').click()
  await page.screenshot({ path: 'artifacts/third-person-controls.png' })
  await page.keyboard.press('ArrowRight')
  assert.notEqual(await read('e.followedId'), firstId)
  await page.keyboard.press('Escape')
  assert.equal(await read('e.cameraMode'), 'review')
  assert.ok(distance(await read('e.camera.position.toArray()'), review.position) < .01)
  assert.ok(distance(await read('e.controls.target.toArray()'), review.target) < .01)
  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByRole('button', { name: '焊工视角', exact: true }).click()
  await page.screenshot({ path: 'artifacts/third-person-mobile.png', fullPage: true })
  assert.ok(await page.evaluate('document.documentElement.scrollWidth <= innerWidth'))
  assert.deepEqual(errors, [])
  console.log('PASS: wheel distance, first/third-person blend, panel speed/reset, switching and view restore; no runtime errors')
} finally { await browser.close() }
