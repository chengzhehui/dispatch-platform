import { browserLaunchOptions } from './browser-options.mjs'
import { chromium } from 'playwright'
import fs from 'node:fs'
import assert from 'node:assert/strict'

fs.mkdirSync('artifacts', { recursive: true })
const browser = await chromium.launch(browserLaunchOptions)
const page = await browser.newPage({ viewport: { width: 1536, height: 1024 } })
page.setDefaultTimeout(60000)
const errors = []
page.on('response', response => { if (response.status() >= 400) errors.push(`HTTP ${response.status()} ${response.url()}`) })
page.on('pageerror', error => errors.push(error.message))
page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
const engine = `document.getElementById('app').__vue_app__._instance.setupState.engine`
const evaluate = expression => page.evaluate(`${engine} && (${expression})`)
const wait = expression => page.waitForFunction(`${engine} && (${expression})`, null, { timeout: 90000 })
const distance = (a, b) => Math.hypot(...a.map((value, i) => value - b[i]))
const snapshotCamera = () => evaluate(`({position:${engine}.camera.position.toArray(), target:${engine}.controls.target.toArray(), direction:${engine}.camera.position.clone().sub(${engine}.controls.target).normalize().toArray()})`)
async function drag(x, y, button, shift = false) {
  await page.mouse.move(x, y)
  if (shift) await page.keyboard.down('Shift')
  await page.mouse.down({ button }); await page.mouse.move(x + 80, y + 24, { steps: 8 }); await page.mouse.up({ button })
  if (shift) await page.keyboard.up('Shift')
  await page.waitForTimeout(900)
}
async function setCount(count) {
  await page.getByLabel('今日焊工人数').fill(String(count))
  await page.getByRole('button', { name: '设置人数', exact: true }).click()
  await wait(`${engine}.workers.filter(w=>w.unit===${engine}.unit).length === ${count}`)
}
async function switchUnit(unit) {
  await page.locator('.unit-row').filter({ has: page.locator('strong', { hasText: new RegExp(`^${unit}$`) }) }).click()
  await wait(`${engine}.unit === '${unit}' && ${engine}.tiles.visibleTiles.size > 0`)
}
try {
  await page.goto('http://localhost:5188')
  await wait(`${engine}.workers.length === 12 && ${engine}.tiles.visibleTiles.size > 0`)
  assert.equal(await evaluate(`${engine}.workerAssetReady`), true)
  assert.equal(await evaluate(`${engine}.workers[0].visual.assetName`), 'Quaternius Worker')
  assert.ok(await evaluate(`${engine}.workers[0].visual.mixer._actions.length >= 2`))
  const actualHeight = await page.evaluate(async () => {
    const { Box3 } = await import('/node_modules/three/build/three.module.js')
    const worker = document.getElementById('app').__vue_app__._instance.setupState.engine.workers[0]
    const bounds = new Box3().setFromObject(worker.visual.model, true)
    return bounds.max.y - bounds.min.y
  })
  assert.ok(actualHeight > 1.7 && actualHeight < 2, 'skinned character renders at adult height')
  assert.equal(await evaluate(`${engine}.speed`), 16)
  assert.equal(await evaluate(`${engine}.site.groundElevation`), 81.105)
  console.log('PASS: local animated GLB, 16 m/s default and 213 platform elevation')

  const beforeGeneration = await evaluate(`${engine}.generation`)
  await page.locator('.unit-row.active').click()
  assert.equal(await evaluate(`${engine}.generation`), beforeGeneration)
  const canvas = await page.locator('.scene-host').boundingBox()
  const panBefore = await snapshotCamera()
  await drag(canvas.x + canvas.width * 0.4, canvas.y + canvas.height * 0.65, 'middle')
  const panAfter = await snapshotCamera()
  assert.ok(distance(panBefore.target, panAfter.target) > 1, 'middle drag pans target')
  assert.ok(distance(panBefore.direction, panAfter.direction) < 0.02, 'pan preserves direction')
  await drag(canvas.x + canvas.width * 0.4, canvas.y + canvas.height * 0.65, 'middle', true)
  const orbitAfter = await snapshotCamera()
  assert.ok(distance(panAfter.direction, orbitAfter.direction) > 0.1, 'Shift-middle rotates')
  assert.ok(distance(panAfter.target, orbitAfter.target) < 0.5, 'orbit keeps target')
  await drag(canvas.x + canvas.width * 0.4, canvas.y + canvas.height * 0.65, 'right')
  const rightAfter = await snapshotCamera()
  assert.ok(distance(rightAfter.position, orbitAfter.position) < 0.5, 'right drag preserves view')
  console.log('PASS: middle pan, Shift-middle orbit, right reserved, active-unit no-op')

  await setCount(6)
  for (const [unit, count] of [['27', 3], ['37', 4], ['38', 2], ['39', 1]]) {
    await switchUnit(unit)
    assert.equal(await page.getByLabel('今日焊工人数').inputValue(), '0')
    await setCount(count)
    assert.equal(await evaluate(`${engine}.workers.filter(w=>w.unit==='213').length`), 6)
  }
  await switchUnit('27'); await setCount(1)
  assert.equal(await evaluate(`${engine}.workers.filter(w=>w.unit==='37').length`), 4)
  assert.equal(await evaluate(`${engine}.workers.filter(w=>w.unit==='213').length`), 6)
  assert.equal(await evaluate(`new Set(${engine}.workers.map(w=>w.id)).size === ${engine}.workers.length`), true)
  console.log('PASS: independent counts in all 5 units, reduction isolation, unique IDs')

  await switchUnit('213')
  assert.equal(await page.getByLabel('今日焊工人数').inputValue(), '6')
  await page.getByLabel('地面标高', { exact: true }).fill('82')
  await page.getByRole('button', { name: '校准', exact: true }).click()
  assert.equal(await evaluate(`${engine}.tiles.group.position.y`), -82)
  assert.equal(await evaluate(`${engine}.sites['27'].groundElevation`), 73)
  await wait(`${engine}.tiles.stats.queued === 0 && ${engine}.tiles.stats.downloading === 0 && ${engine}.tiles.stats.parsing === 0`)
  await page.reload(); await wait(`${engine}.workers.length === 14 && ${engine}.tiles.visibleTiles.size > 0`)
  assert.equal(await evaluate(`${engine}.site.groundElevation`), 82)
  assert.equal(await evaluate(`${engine}.workers.filter(w=>w.unit==='27').length`), 1)
  await page.getByLabel('地面标高', { exact: true }).fill('81.105')
  await page.getByRole('button', { name: '校准', exact: true }).click()
  console.log('PASS: ground calibration and multi-unit persistence with non-sequential IDs')

  await page.keyboard.press('ArrowRight')
  assert.equal(await evaluate(`${engine}.cameraMode`), 'worker')
  const firstId = await evaluate(`${engine}.followedId`)
  await page.keyboard.press('ArrowRight')
  assert.notEqual(await evaluate(`${engine}.followedId`), firstId)
  await page.keyboard.press('ArrowLeft')
  assert.equal(await evaluate(`${engine}.followedId`), firstId)
  await page.getByRole('button', { name: '下一名焊工', exact: true }).click()
  assert.notEqual(await evaluate(`${engine}.followedId`), firstId)
  await page.getByLabel('视角跟随焊工').selectOption(firstId)
  assert.equal(await evaluate(`${engine}.followedId`), firstId)
  assert.equal(await evaluate(`${engine}.workers.find(w=>w.id==='${firstId}').visual.root.visible`), true)
  await evaluate(`${engine}.command([${engine}.site.minX+30, .1, ${engine}.site.minZ+30])`)
  await page.waitForTimeout(400)
  assert.ok(await evaluate(`${engine}.camera.position.y > ${engine}.workers.find(w=>w.id==='${firstId}').position[1] + 1`))
  assert.ok(await evaluate(`Math.hypot(${engine}.camera.position.x - ${engine}.workers.find(w=>w.id==='${firstId}').position[0], ${engine}.camera.position.z - ${engine}.workers.find(w=>w.id==='${firstId}').position[2]) > 3`))
  await page.screenshot({ path: 'artifacts/worker-view.png' })
  await page.keyboard.press('Escape')
  assert.equal(await evaluate(`${engine}.cameraMode`), 'review')
  await page.getByLabel('今日焊工人数').focus(); await page.keyboard.press('ArrowRight')
  assert.equal(await evaluate(`${engine}.cameraMode`), 'review', 'inputs retain native arrows')
  await page.getByLabel('今日焊工人数').blur()
  await page.getByRole('button', { name: '焊工视角', exact: true }).click()
  await setCount(0)
  assert.equal(await evaluate(`${engine}.cameraMode`), 'review', 'deleting followed worker exits view')
  assert.equal(await evaluate(`${engine}.followedId`), null)
  assert.equal(await evaluate(`${engine}.workers.filter(w=>w.unit==='37').length`), 4)
  await setCount(6)
  console.log('PASS: arrows, camera panel, third-person tracking, Esc, followed-worker removal')

  const generation = await evaluate(`${engine}.generation`)
  await page.getByRole('button', { name: '重新加载', exact: true }).click()
  await wait(`${engine}.generation === ${generation + 1} && ${engine}.tiles.visibleTiles.size > 0`)
  await page.waitForTimeout(1500)
  await page.screenshot({ path: 'artifacts/desktop-updated.png' })
  await page.getByRole('button', { name: '预备区', exact: true }).click(); await page.waitForTimeout(500)
  await page.screenshot({ path: 'artifacts/workers-updated.png' })
  await page.setViewportSize({ width: 390, height: 844 }); await page.waitForTimeout(500)
  assert.ok(await page.evaluate('document.documentElement.scrollWidth <= innerWidth'))
  await page.screenshot({ path: 'artifacts/mobile-updated.png', fullPage: true })
  assert.deepEqual(errors, [], 'no runtime or resource errors')
  console.log('PASS: explicit reload and desktop/mobile layouts; no runtime/resource errors')
} finally { await browser.close() }
