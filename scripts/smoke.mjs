import { browserLaunchOptions } from './browser-options.mjs'
import { chromium } from 'playwright'
import fs from 'node:fs'
import assert from 'node:assert/strict'
fs.mkdirSync('artifacts', { recursive: true })
const browser = await chromium.launch(browserLaunchOptions)
const page = await browser.newPage({ viewport: { width: 1536, height: 1024 } })
page.setDefaultTimeout(60000)
const errors = []
page.on('response', r => { if (r.status() >= 400) errors.push(`HTTP ${r.status()} ${r.url()}`) })
page.on('pageerror', e => errors.push(e.message))
page.on('console', m => { if (m.type() === 'error') errors.push(m.text()) })
const engine = `document.getElementById('app').__vue_app__._instance.setupState.engine`
try {
  await page.goto('http://localhost:5188')
  await page.getByRole('button', { name: '设置人数', exact: true }).waitFor()
  await page.waitForFunction(`${engine}?.workers.length === 12`, { timeout: 60000 })
  await page.waitForFunction(`${engine}?.loaded > 3`, { timeout: 90000 })
  await page.waitForFunction(`${engine}?.tiles.visibleTiles.size > 0`)
  console.log('PASS: initial real model rendered')
  await page.waitForTimeout(2500)
  await page.screenshot({ path: 'artifacts/desktop.png' })
  await page.getByLabel('今日焊工人数').fill('6'); await page.getByRole('button', { name: '设置人数', exact: true }).click()
  assert.equal(await page.evaluate(`${engine}.workers.length`), 6)
  await page.getByRole('button', { name: '预备区', exact: true }).click()
  await page.waitForTimeout(1000)
  const workerPoint = await page.evaluate(`(() => { const e=${engine}, v=e.workers[0].visual.root.position.clone(); v.y+=1; v.project(e.camera); const r=e.host.getBoundingClientRect(); return { x:r.x+(v.x+1)/2*r.width, y:r.y+(1-v.y)/2*r.height } })()`)
  await page.mouse.click(workerPoint.x, workerPoint.y)
  assert.equal(await page.evaluate(`${engine}.selected.size`), 1, 'click actual worker in canvas')
  console.log('PASS: count adjustment and canvas worker selection')
  await page.screenshot({ path: 'artifacts/selected-worker.png' })
  await page.getByRole('button', { name: '全景', exact: true }).click(); await page.waitForTimeout(1000)
  const destination = await page.evaluate(`(() => { const e=${engine}, v=e.workers[0].visual.root.position.clone(); v.set(e.site.minX+e.size*.5,.1,e.site.minZ+e.size*.5); v.project(e.camera); const r=e.host.getBoundingClientRect(); return { x:r.x+(v.x+1)/2*r.width, y:r.y+(1-v.y)/2*r.height } })()`)
  await page.mouse.click(destination.x, destination.y)
  assert.ok(await page.evaluate(`${engine}.workers[0].target`), 'canvas click issues movement command')
  await page.getByRole('button', { name: '暂停移动', exact: true }).click()
  const before = await page.evaluate(`${engine}.workers[0].position`); await page.waitForTimeout(400)
  assert.deepEqual(await page.evaluate(`${engine}.workers[0].position`), before, 'pause stops simulation')
  await page.getByRole('button', { name: '继续移动', exact: true }).click()
  await page.locator('.simulation-controls select').selectOption('60')
  await page.waitForFunction(`${engine}.workers[0].target === null`, { timeout: 20000 })
  assert.ok(await page.evaluate(`${engine}.workers[0].position[0] > ${engine}.site.minX`), 'worker reached model work zone')
  await page.waitForTimeout(250)
  assert.equal(await page.locator('.zone-cell.occupied strong').first().innerText(), '1 人')
  console.log('PASS: movement, pause/resume and zone occupancy')
  await page.screenshot({ path: 'artifacts/dispatched.png' })
  await page.getByRole('button', { name: '27 0 人', exact: true }).click()
  await page.waitForFunction(`${engine}.unit === '27' && ${engine}.loaded > 0`, { timeout: 60000 })
  assert.equal(await page.evaluate(`${engine}.workers.filter(w=>w.unit==='213').length`), 6)
  await page.getByLabel('今日焊工人数').fill('8'); await page.getByRole('button', { name: '设置人数', exact: true }).click()
  assert.equal(await page.evaluate(`${engine}.workers.filter(w=>w.unit==='27').length`), 8)
  // Let visible requests finish before navigation: Chromium reports document-
  // teardown cancellations as TypeError rather than AbortError in fetch.
  await page.waitForFunction(`${engine}.tiles.stats.queued === 0 && ${engine}.tiles.stats.downloading === 0 && ${engine}.tiles.stats.parsing === 0`, null, { timeout: 90000 })
  await page.reload(); await page.waitForFunction(`${engine}?.workers.length === 14`, { timeout: 60000 })
  assert.equal(await page.evaluate(`${engine}.workers.filter(w=>w.unit==='27').length`), 8, 'browser reload restores unit roster')
  console.log('PASS: unit roster and persistence')
  for (const unit of ['37','38','39']) {
    await page.getByRole('button', { name: `${unit} 0 人`, exact: true }).click()
    await page.waitForFunction(`${engine}.unit === '${unit}' && ${engine}.loaded > 0`, { timeout: 60000 })
  }
  await page.getByRole('button', { name: '213 6 人', exact: true }).click()
  await page.waitForFunction(`${engine}.unit === '213' && ${engine}.loaded > 0`)
  await page.setViewportSize({ width: 390, height: 844 }); await page.waitForTimeout(500)
  assert.ok(await page.evaluate('document.documentElement.scrollWidth <= innerWidth'), 'mobile has no horizontal overflow')
  await page.screenshot({ path: 'artifacts/mobile.png', fullPage: true })
  assert.deepEqual(errors, [], 'no runtime or console errors')
  console.log('PASS: real model loading (5 units), crew sizing, canvas worker pick, canvas movement, pause/resume, zone occupancy, per-unit roster, browser persistence, mobile layout. No runtime errors.')
} finally { await browser.close() }
